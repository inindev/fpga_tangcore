#!/usr/bin/env python3
# Write each core's src/iosys/gowin_dpb_menu.v: the menu's text BRAM and font ROM (see
# textdisp.v), each a 2 KB Gowin DPB block. The font is the same in all seven cores; each
# file keeps its own logo and initial character buffer, read from the file as it is.
#
# Font, one glyph per Latin-1 code:
#   0x00-0x1F  the menu's extra glyphs below
#   0x20-0x7F  ASCII, kept from the file (Daniel Hepper's font8x8_basic)
#   0x80-0x9F  blank: the volume bar's bitmap, written by the firmware (iosys command 0x10)
#   0xA0-0xFF  scripts/font8x8_ext_latin.h (Daniel Hepper, public domain)
#
#   scripts/font_glyphs.py                    write the cores' gowin_dpb_menu.v
#   scripts/font_glyphs.py --check            list cores whose file differs (exit 1 if any)
#   scripts/font_glyphs.py --preview out.png  draw the font and a sample file chooser screen
#   scripts/font_glyphs.py --logo <core> logo.txt
#                                             set a core's logo: 14 lines of 72 '0'/'1'
#                                             (fpga_monitorcore/scripts/genlogo.py writes one)
#
# Codes must match the BOX_* and GLYPH_* names in fpga_firmware-bl616/ui/overlay.h.
# 0x09, 0x0A and 0x0D (tab, newline, return) stay blank: the firmware prints "\n" in places.

import os
import re
import struct
import sys
import zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CORES = ["fpga_nestang", "fpga_snestang", "fpga_smstang", "fpga_gbatang",
         "fpga_monitorcore", "fpga_mdtang", "fpga_pctang"]

# 8x8, top row first, leftmost pixel first ('#' on). Single lines on row/column 3, double
# lines on rows/columns 2 and 4, the same middle as the letters (columns and rows 0-6).
GLYPHS = {
    0x01: "........ ........ ........ ######## ........ ........ ........ ........",  # ─
    0x02: "...#.... ...#.... ...#.... ...#.... ...#.... ...#.... ...#.... ...#....",  # │
    0x03: "........ ........ ........ ...##### ...#.... ...#.... ...#.... ...#....",  # ┌
    0x04: "........ ........ ........ ####.... ...#.... ...#.... ...#.... ...#....",  # ┐
    0x05: "...#.... ...#.... ...#.... ...##### ........ ........ ........ ........",  # └
    0x06: "...#.... ...#.... ...#.... ####.... ........ ........ ........ ........",  # ┘
    0x07: "...#.... ...#.... ...#.... ...##### ...#.... ...#.... ...#.... ...#....",  # ├
    0x08: "...#.... ...#.... ...#.... ####.... ...#.... ...#.... ...#.... ...#....",  # ┤
    0x0B: "........ ........ ######## ........ ######## ........ ........ ........",  # ═
    0x0C: "..#.#... ..#.#... ..#.#... ..#.#... ..#.#... ..#.#... ..#.#... ..#.#...",  # ║
    0x0E: "........ ........ ..###### ..#..... ..#.#### ..#.#... ..#.#... ..#.#...",  # ╔
    0x0F: "........ ........ #####... ....#... ###.#... ..#.#... ..#.#... ..#.#...",  # ╗
    0x10: "..#.#... ..#.#... ..#.#### ..#..... ..###### ........ ........ ........",  # ╚
    0x11: "..#.#... ..#.#... ###.#... ....#... #####... ........ ........ ........",  # ╝
    0x12: "..#.#... ..#.#... ..#.#### ..#..... ..#.#### ..#.#... ..#.#... ..#.#...",  # ╠
    0x13: "..#.#... ..#.#... ###.#... ....#... ###.#... ..#.#... ..#.#... ..#.#...",  # ╣
    0x14: "........ ...#.... ..###... .#####.. #######. ........ ........ ........",  # ▲
    0x15: "........ ........ #######. .#####.. ..###... ...#.... ........ ........",  # ▼
    0x16: "....#... ...##... ..###... .####... ..###... ...##... ....#... ........",  # ◄
    0x17: ".#...... .##..... .###.... .####... .###.... .##..... .#...... ........",  # ►
    0x18: "........ ###..... #######. #######. #######. #######. #######. ........",  # folder
    0x19: ".####... .#..##.. .#...#.. .#...#.. .#...#.. .#...#.. .#####.. ........",  # file
    0x1A: ".#####.. ###.###. ##.#.##. #.###.#. #.....#. #.###.#. .#####.. ........",  # A button
    0x1B: ".#####.. #....##. #.###.#. #....##. #.###.#. #....##. .#####.. ........",  # B button
    0x1C: "........ ........ ........ ........ ........ ........ .#.#.#.. ........",  # …
}


# The two 2 KB blocks as one 4 KB image: text BRAM at $000, font ROM at $800
MEM_SIZE = 4096
LOGO_BASE = 0x380               # logo in the text BRAM, 14 rows of 9 bytes
HL_BASE = 0x400                 # highlight bar registers in the text BRAM: row, first, last column
FONT_BASE = 0x800               # font ROM, 8 bytes per character
LATIN1_H = os.path.join(ROOT, "scripts", "font8x8_ext_latin.h")
INIT_RE = re.compile(r"^defparam dpb_inst_([01])\.INIT_RAM_([0-9A-F]{2}) = 256'h([0-9A-Fa-f]{64});",
                     re.M)

HEADER = """\
// Menu memories for textdisp.v, each one Gowin DPB block of 2048 x 8 bits:
// dpb_inst_0, the text BRAM: written on clka (port A), read on clkb (port B).
//   $000-$37F character buffer, $380-$3FD logo, $400-$402 highlight bar registers
// dpb_inst_1, the font, read on clkb: 256 Latin-1 characters of 8 bytes. Port A writes it on
//   clka (wref, adfa, dina); textdisp.v only lets codes 0x80-0x9F be written.
//
// Generated by scripts/font_glyphs.py, which keeps the logo: edit the font there.

module gowin_dpb_menu (clka, wrea, ada, dina, wref, adfa, clkb, adb, doutb, adf, doutf);

input clka;
input wrea;
input [10:0] ada;
input [7:0] dina;
input wref;
input [10:0] adfa;
input clkb;
input [10:0] adb;
output [7:0] doutb;
input [10:0] adf;
output [7:0] doutf;

wire gw_gnd = 1'b0;
wire gw_vcc = 1'b1;
wire [15:0] dpb_inst_0_douta;
wire [7:0] dpb_inst_0_doutb_w;
wire [15:0] dpb_inst_1_douta;
wire [7:0] dpb_inst_1_doutf_w;

DPB dpb_inst_0 (
    .DOA(dpb_inst_0_douta),
    .DOB({dpb_inst_0_doutb_w, doutb}),
    .CLKA(clka),
    .OCEA(gw_vcc),
    .CEA(gw_vcc),
    .RESETA(gw_gnd),
    .WREA(wrea),
    .CLKB(clkb),
    .OCEB(gw_vcc),
    .CEB(gw_vcc),
    .RESETB(gw_gnd),
    .WREB(gw_gnd),
    .BLKSELA({gw_gnd, gw_gnd, gw_gnd}),
    .BLKSELB({gw_gnd, gw_gnd, gw_gnd}),
    .ADA({ada, gw_gnd, gw_gnd, gw_gnd}),
    .DIA({8'b0, dina}),
    .ADB({adb, gw_gnd, gw_gnd, gw_gnd}),
    .DIB(16'b0)
);

DPB dpb_inst_1 (
    .DOA(dpb_inst_1_douta),
    .DOB({dpb_inst_1_doutf_w, doutf}),
    .CLKA(clka),
    .OCEA(gw_gnd),
    .CEA(gw_vcc),
    .RESETA(gw_gnd),
    .WREA(wref),
    .CLKB(clkb),
    .OCEB(gw_vcc),
    .CEB(gw_vcc),
    .RESETB(gw_gnd),
    .WREB(gw_gnd),
    .BLKSELA({gw_gnd, gw_gnd, gw_gnd}),
    .BLKSELB({gw_gnd, gw_gnd, gw_gnd}),
    .ADA({adfa, gw_gnd, gw_gnd, gw_gnd}),
    .DIA({8'b0, dina}),
    .ADB({adf, gw_gnd, gw_gnd, gw_gnd}),
    .DIB(16'b0)
);
"""

PARAMS = """
defparam dpb_inst_{n}.READ_MODE0 = 1'b0;
defparam dpb_inst_{n}.READ_MODE1 = 1'b0;
defparam dpb_inst_{n}.WRITE_MODE0 = 2'b00;
defparam dpb_inst_{n}.WRITE_MODE1 = 2'b00;
defparam dpb_inst_{n}.BIT_WIDTH_0 = 8;
defparam dpb_inst_{n}.BIT_WIDTH_1 = 8;
defparam dpb_inst_{n}.BLK_SEL_0 = 3'b000;
defparam dpb_inst_{n}.BLK_SEL_1 = 3'b000;
defparam dpb_inst_{n}.RESET_MODE = "SYNC";
"""


def glyph_bytes():
    """Font bytes for codes 0x00-0x1F, bit 0 = leftmost pixel."""
    out = bytearray(32 * 8)
    for code, art in GLYPHS.items():
        rows = art.split()
        assert len(rows) == 8 and all(len(r) == 8 for r in rows), hex(code)
        for y, row in enumerate(rows):
            out[code * 8 + y] = sum(1 << x for x, c in enumerate(row) if c == "#")
    return out


def latin1_bytes():
    """Font bytes for codes 0x80-0xFF: 0x80-0x9F blank, 0xA0-0xFF from Hepper's header."""
    with open(LATIN1_H) as f:
        rows = re.findall(r"^\s*\{((?:\s*0x[0-9A-Fa-f]{2}\s*,?){8})\}", f.read(), re.M)
    assert len(rows) == 96, "%s: %d glyphs, expected 96" % (LATIN1_H, len(rows))
    out = bytearray(32 * 8)
    for row in rows:
        out += bytes(int(v, 16) for v in row.replace(",", " ").split())
    return out


def read_bram(text):
    """The memories in a gowin_dpb_menu.v, as the 4 KB image. The earlier file (one 2 KB
    block: text at $000, 128-character font at $400) is read too."""
    blocks = [bytearray(2048), bytearray(2048)]
    for m in INIT_RE.finditer(text):
        i = int(m.group(2), 16) * 32
        blocks[int(m.group(1))][i:i + 32] = bytes.fromhex(m.group(3))[::-1]   # byte 31 first
    mem = bytearray(MEM_SIZE)
    if "DPB dpb_inst_1" in text:
        mem[:2048], mem[FONT_BASE:] = blocks
    else:
        mem[:0x400] = blocks[0][:0x400]
        mem[FONT_BASE:FONT_BASE + 0x400] = blocks[0][0x400:]
        mem[HL_BASE:HL_BASE + 3] = bytes([0xFF, 1, 30])     # no highlight
    return mem


def update_font(mem, glyphs, latin1):
    mem[FONT_BASE:FONT_BASE + len(glyphs)] = glyphs
    mem[FONT_BASE + 0x400:] = latin1
    return mem


def write_bram(mem):
    out = [HEADER]
    for n in range(2):
        out.append(PARAMS.format(n=n))
        block = mem[n * 2048:(n + 1) * 2048]
        for i in range(64):
            out.append("defparam dpb_inst_%d.INIT_RAM_%02X = 256'h%s;\n"
                       % (n, i, block[i * 32:i * 32 + 32][::-1].hex().upper()))
    out.append("\nendmodule //gowin_dpb_menu\n")
    return "".join(out)


def png(path, w, h, rgb):
    raw = b"".join(b"\0" + bytes(rgb[y * w * 3:(y + 1) * w * 3]) for y in range(h))
    def chunk(t, d):
        return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d))
    with open(path, "wb") as f:
        f.write(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0))
                + chunk(b"IDAT", zlib.compress(raw)) + chunk(b"IEND", b""))


def sample_screen():
    """32x28 file chooser screen as the firmware draws it (no logo): frame rows 5-24 with
    the path and page in the top edge, icons, scroll marker, hints on row 25."""
    s = [[" "] * 32 for _ in range(28)]
    def put(x, y, text):
        for i, ch in enumerate(text):
            s[y][x + i] = ch
    top = "\x0e" + "\x0b" * 30 + "\x0f"
    put(0, 5, top)
    put(2, 5, " nes/Super Mario ")
    put(25, 5, " 1/3 ")
    for y in range(6, 24):
        put(0, y, "\x0c")
        put(31, y, "\x0c")
    put(0, 24, "\x10" + "\x0b" * 30 + "\x11")
    rows = [("\x18", ".."), ("\x18", "Hacks"), ("\x19", "Super Mario Bros (W).nes"),
            ("\x19", "Super Mario Bros 3 (USA) (Rev 1).nes"), ("\x19", "720°.nes"),
            ("\x19", "Pokémon Crystal (Español).gbc"), ("\x19", "Ça Bouge à São Tomé (Ü).sfc")]
    for i, (icon, name) in enumerate(rows):
        if len(name) > 26:
            name = name[:25] + "\x1c"
        put(2, 6 + i, icon + " " + name)
    put(1, 8, ">")
    put(30, 23, "\x15")
    put(7, 25, "\x1a\x1b Select  \x16\x17 Page")
    return s


def preview(path, font):
    """Left: all 256 characters (16x16). Right: a sample file chooser screen."""
    text, frame, back = (255, 255, 255), (90, 90, 90), (0, 0, 0)
    cols, rows, scale = 52, 28, 3
    grid = [[" "] * cols for _ in range(rows)]
    for c in range(256):
        grid[2 + c // 16][1 + c % 16] = chr(c)
    for y, line in enumerate(sample_screen()):
        for x, ch in enumerate(line):
            grid[y][19 + x] = ch
    W, H = cols * 8 * scale, rows * 8 * scale
    rgb = bytearray(W * H * 3)
    for py in range(H):
        for px in range(W):
            x, y = px // scale, py // scale
            bits = font[ord(grid[y // 8][x // 8]) * 8 + y % 8]
            on = bits >> (x % 8) & 1
            i = (py * W + px) * 3
            rgb[i:i + 3] = bytes(text if on else frame if x // 8 in (18, 51) else back)
    png(path, W, H, rgb)


def logo_bytes(path):
    """The logo for $380: 14 rows of 72 pixels, 9 bytes a row, bit 0 = leftmost pixel. The
    file holds the rows as lines of 72 '0'/'1' characters; other lines are ignored."""
    with open(path) as f:
        rows = [l.strip() for l in f if re.fullmatch(r"[01]{72}", l.strip())]
    if len(rows) != 14:
        raise SystemExit("%s: %d rows of 72 '0'/'1', expected 14" % (path, len(rows)))
    out = bytearray(128)
    for i in range(126):
        bits = rows[i // 9][i % 9 * 8:i % 9 * 8 + 8]
        out[i] = sum(1 << k for k, c in enumerate(bits) if c == "1")
    return out


def main():
    args = sys.argv[1:]
    glyphs, latin1 = glyph_bytes(), latin1_bytes()
    if args[:1] == ["--logo"] and len(args) == 3 and args[1] in CORES:
        path = os.path.join(ROOT, args[1], "src/iosys/gowin_dpb_menu.v")
        with open(path) as f:
            mem = update_font(read_bram(f.read()), glyphs, latin1)
        mem[LOGO_BASE:LOGO_BASE + 128] = logo_bytes(args[2])
        with open(path, "w") as f:
            f.write(write_bram(mem))
        print("updated: %s" % os.path.relpath(path, ROOT))
        return 0
    if args[:1] == ["--preview"] and len(args) == 2:
        path = os.path.join(ROOT, CORES[0], "src/iosys/gowin_dpb_menu.v")
        with open(path) as f:
            font = update_font(read_bram(f.read()), glyphs, latin1)[FONT_BASE:]
        preview(args[1], font)
        return 0
    if args not in ([], ["--check"]):
        print("usage: %s [--check | --preview out.png | --logo <core> logo.txt]" % sys.argv[0],
              file=sys.stderr)
        return 2
    rc = 0
    for core in CORES:
        path = os.path.join(ROOT, core, "src/iosys/gowin_dpb_menu.v")
        with open(path) as f:
            text = f.read()
        new = write_bram(update_font(read_bram(text), glyphs, latin1))
        if new == text:
            continue
        if args:
            print("differs: %s" % os.path.relpath(path, ROOT))
            rc = 1
        else:
            with open(path, "w") as f:
                f.write(new)
            print("updated: %s" % os.path.relpath(path, ROOT))
    return rc


if __name__ == "__main__":
    sys.exit(main())
